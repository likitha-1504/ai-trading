"""TradePlan query endpoints."""

from fastapi import APIRouter, Depends, HTTPException, Query, status

from app.api.deps import get_db_repo
from app.db.repository import DatabaseRepository
from app.models.contracts import TradePlan

router = APIRouter()


@router.get(
    "",
    response_model=list[TradePlan],
    summary="List evaluated TradePlans",
    description="Returns TradePlans generated by the Deterministic Trade Gate, with approval status and risk limits.",
)
def list_trade_plans(
    approval_mode: str | None = Query(
        default=None, description="Filter by approval mode (AUTONOMOUS, MANUAL_PENDING, etc.)"
    ),
    symbol: str | None = Query(default=None, description="Filter by ticker symbol"),
    limit: int = Query(default=50, ge=1, le=200, description="Max trade plans to return"),
    repo: DatabaseRepository = Depends(get_db_repo),
) -> list[TradePlan]:
    plans = repo.get_recent_trade_plans(limit=limit)
    if approval_mode:
        plans = [p for p in plans if p.approval_mode.value == approval_mode.upper()]
    if symbol:
        plans = [p for p in plans if p.symbol == symbol.upper()]
    return plans


@router.get(
    "/{plan_id}",
    response_model=TradePlan,
    summary="Get TradePlan details by ID",
    description="Returns all 13 fields of the synthesized TradePlan contract.",
)
def get_trade_plan_by_id(
    plan_id: str,
    repo: DatabaseRepository = Depends(get_db_repo),
) -> TradePlan:
    plan = repo.get_trade_plan(plan_id)
    if not plan:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"TradePlan {plan_id} not found",
        )
    return plan
